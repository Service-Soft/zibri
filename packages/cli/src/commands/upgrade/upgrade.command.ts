import { version } from '../../../package.json';
import { ScaffoldAnswers, ScaffoldManifest, ScaffoldUtilities } from '../../scaffold';
import { exitWithError, getPath, Path } from '../../utilities';
import { RegeneratingCommand } from '../regenerating-command.model';

/**
 * What an upgrade works on.
 */
type UpgradeInput = {
    /**
     * The project.
     */
    projectPath: Path,
    /**
     * What was generated into it last, or undefined for a project from before there was a manifest.
     */
    manifest: ScaffoldManifest | undefined,
    /**
     * What it is generated from this time.
     */
    answers: ScaffoldAnswers
};

/**
 * One release of a version, as numbers: major, minor and patch, and whether it is a pre-release.
 */
type VersionOrder = [number, number, number, number];

/**
 * Where a version sits among the others.
 * @param value - The version, as `major.minor.patch` with an optional pre-release.
 * @returns What it is compared by.
 */
function resolveVersionOrder(value: string): VersionOrder {
    const [release = '', preRelease]: string[] = value.split('-');
    const [major = 0, minor = 0, patch = 0]: number[] = release.split('.').map(Number);
    // a pre-release comes before the release it leads up to
    return [major, minor, patch, preRelease == undefined ? 1 : 0];
}

/**
 * Whether one version is a later release than another.
 * @param version - The version in question.
 * @param than - The version it is compared to.
 * @returns True when it is later.
 */
function isLater(version: string, than: string): boolean {
    const other: VersionOrder = resolveVersionOrder(than);
    for (const [index, part] of resolveVersionOrder(version).entries()) {
        const otherPart: number = other[index] ?? 0;
        if (part !== otherPart) {
            return part > otherPart;
        }
    }
    return false;
}

/**
 * Brings a project `zi new` generated to what this release generates.
 *
 * Installs the framework at this release, and what the generator now installs that the project lacks.
 * Then generates the project again, and merges each file into the one the project has.
 */
export class UpgradeCommand extends RegeneratingCommand<UpgradeInput> {
    protected override maxLength: number | undefined = 3;

    protected override async run(input: UpgradeInput): Promise<void> {
        const { projectPath, manifest, answers } = input;
        if (manifest != undefined && isLater(manifest.version, version)) {
            await exitWithError(
                `This project was generated by zibri-cli ${manifest.version}, and this is ${version}. Upgrade the cli first.`
            );
        }

        await this.installDependencies(projectPath, ScaffoldUtilities.resolveDependencies(answers.features), true);
        await this.regenerate(projectPath, manifest, answers, `zi new ${version}`);
    }

    // `zi upgrade [ci] [defaultAuth]`: what the command line names replaces what was recorded, and a
    // project without a manifest is asked for what it does not name
    protected override async resolveInput(args: string[]): Promise<UpgradeInput> {
        const [, ci, defaultAuth]: (string | undefined)[] = args;
        const projectPath: Path = getPath('.');
        const manifest: ScaffoldManifest | undefined = await ScaffoldUtilities.findManifest(projectPath);
        if (manifest != undefined) {
            return {
                projectPath,
                manifest,
                answers: {
                    name: manifest.answers.name,
                    ci: ci == undefined ? manifest.answers.ci : await ScaffoldUtilities.resolveContinuousIntegration(ci),
                    defaultAuth: defaultAuth == undefined
                        ? manifest.answers.defaultAuth
                        : await ScaffoldUtilities.resolveDefaultAuth(defaultAuth),
                    features: manifest.answers.features
                }
            };
        }
        return {
            projectPath,
            manifest,
            answers: {
                name: (await ScaffoldUtilities.resolvePackageJson(projectPath)).name,
                ci: await ScaffoldUtilities.resolveContinuousIntegration(ci),
                defaultAuth: await ScaffoldUtilities.resolveDefaultAuth(defaultAuth),
                features: await ScaffoldUtilities.resolveFeatures(undefined)
            }
        };
    }
}
